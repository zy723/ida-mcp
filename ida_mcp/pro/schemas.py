"""Server-side schema definitions for the ported ida-pro-mcp tools.

Pure typing constructs (TypedDicts and result shapes) mirroring the runtime
bundle: zeromcp derives the JSON schemas from the annotated wrapper
signatures in tools.py, which import their types from here. This module has
no IDA imports and is safe to load in the server process (and in tests).

The source of truth is the runtime bundle; test_pro_signature_parity.py
re-executes the runtime with mocked IDA modules and asserts that the wrapper
signatures stay in sync. Generated by artifacts_port/gen_schemas.py.

Attribution: ported from ida-pro-mcp (MIT) — see ida_mcp/pro/NOTICE.
"""

