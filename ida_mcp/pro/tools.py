"""Server-side @tool wrappers for the ported ida-pro-mcp tools.

Each wrapper mirrors the runtime function's name, parameters, annotations and
docstring so zeromcp derives the upstream JSON schemas, then forwards to
dispatch.call_pro_tool, which executes the runtime bundle in the remote
worker via execute_python and unwraps the {"pro": ...} envelope. The extra
trailing ``instance_id`` parameter carries the official multi-database
semantics. The dbg_* tools are registered like everything else; the
extension gate installed at server start filters them from tools/list and
rejects their tools/call unless the dbg group is enabled
(IDA_MCP_PRO_EXTENSIONS=dbg or --extensions dbg).

Generated by artifacts_port/gen_tools.py; signature drift is fenced by
test_pro_signature_parity.py. Attribution: ported from ida-pro-mcp (MIT) —
see ida_mcp/pro/NOTICE.
"""

